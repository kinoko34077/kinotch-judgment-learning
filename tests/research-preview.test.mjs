import test from "node:test";
import assert from "node:assert/strict";
import worker from "../worker/index.js";
import { listResearchPreviews, evaluateResearchPreview } from "../worker/research-preview.js";
import rules from "../knowledge/domains/uiux/conditional-candidates.v1.json" with { type:"json" };

const origin = "https://example.workers.dev";
const cookie = "__Host-knt_session=" + "A".repeat(50);

test("all 14 research seeds are unapproved, read-only and not generated by an AI", () => {
  const seeds = listResearchPreviews();
  assert.equal(seeds.length, 14);
  assert.equal(new Set(seeds.map(s => s.id)).size, 14);
  assert.equal(seeds.filter(s => s.candidateKnowledgeId).length, 13);
  assert.equal(seeds.filter(s => s.initialStatus === "defer_unmapped_rule").length, 1);
  for (const s of seeds) {
    assert.equal(s.previewOnly, true);
    assert.equal(s.runtimeEligible, false);
    assert.equal(s.modelQuestionGenerated, false);
    assert.equal(s.authority, "research_synthesis_unapproved");
    assert.ok(s.sourceIssue.endsWith("/issues/7"));
  }
});

test("research gate reuses explicit condition/exception/reversal and evidence classes", () => {
  const seedRows = listResearchPreviews();
  let preview = 0, insufficient = 0, unmapped = 0;
  for (const seed of seedRows) {
    const base = evaluateResearchPreview(seed.id, {});
    assert.equal(base.preview_only, true);
    assert.equal(base.go_recorded, false);
    assert.equal(base.human_authorized, false);
    assert.equal(base.rule_actionable, false);
    if (!seed.candidateKnowledgeId) {
      assert.equal(base.status, "defer_unmapped_rule");
      ++unmapped;
      continue;
    }
    assert.equal(base.status, "defer_missing_context");
    const rule = rules.records.find(r => r.id === seed.candidateKnowledgeId);
    assert.ok(rule);
    const selections = Object.fromEntries(seed.facts.map(f => [f.name, "no"]));
    for (const p of rule.applies_when) selections[p.fact] = "yes";
    for (const p of rule.avoid_when) selections[p.fact] = "no";
    for (const r of rule.reversal_conditions) for (const p of r.when) selections[p.fact] = "no";
    const r = evaluateResearchPreview(seed.id, selections);
    const expected = rule.evidence_support_level === "partial_claim_support"
      ? "preview_candidate_only" : "defer_insufficient_evidence";
    assert.equal(r.status, expected, seed.id);
    assert.equal(r.go_recorded, false);
    assert.equal(r.rule_actionable, false);
    if (expected === "preview_candidate_only") ++preview;
    else ++insufficient;
    if (rule.avoid_when.length) {
      const first = rule.avoid_when[0].fact;
      assert.equal(evaluateResearchPreview(seed.id, { ...selections, [first]:"yes" }).status,
        "defer_contraindicated");
    }
    if (rule.reversal_conditions.length) {
      const first = rule.reversal_conditions[0].when[0].fact;
      assert.equal(evaluateResearchPreview(seed.id, { ...selections, [first]:"yes" }).status,
        "defer_reversal");
    }
  }
  assert.deepEqual({preview, insufficient, unmapped}, {preview:5,insufficient:8,unmapped:1});
});

test("invalid or unverified contextual input is rejected without scenario inference", () => {
  for (const [id, context] of [
    ["Q-UNKNOWN", {}], [null, {}], ["Q-BAS-001", null], ["Q-BAS-001", []],
    ["Q-BAS-001", {__proto__:null, attacker:"yes"}],
    ["Q-BAS-001", {data_shape:"malicious"}],
    ["Q-BAS-001", {data_shape:true}]
  ]) assert.throws(() => evaluateResearchPreview(id, context), TypeError);
  assert.equal(evaluateResearchPreview("Q-BAS-001", {data_shape:"unknown"}).status,
    "defer_missing_context");
});

function fakeDb() {
  let other = 0;
  return { get other() { return other; },
    prepare(sql) {
      if (!sql.includes("FROM auth_sessions")) { other++; throw Error("Research preview must never touch answer DB"); }
      return { bind() { return { async first() { return {user_id:"123456"}; } }; } };
    }, batch() { other++; throw Error("Research preview must not persist"); }
  };
}
test("research API is owner-only, bounded and never persists judgment data", async () => {
  const DB = fakeDb();
  const env = {DB,OWNER_GITHUB_USER_ID:"123456",PUBLIC_ORIGIN:origin};
  const anon = await worker.fetch(new Request(origin+"/api/research/seeds"),env);
  assert.equal(anon.status,401);
  const headers = {Cookie:cookie};
  const owner = await worker.fetch(new Request(origin+"/api/research/seeds",{headers}),env);
  assert.equal(owner.status,200);
  const {seeds,researchOnly} = await owner.json();
  assert.equal(researchOnly,true);
  assert.equal(seeds.length,14);
  const evalHeaders = {Cookie:cookie,Origin:origin,"Content-Type":"application/json"};
  const params = {seedId:"Q-BAS-001",selections:{}};
  const evaluated = await worker.fetch(new Request(origin+"/api/research/evaluate",{
    method:"POST",headers:evalHeaders,body:JSON.stringify(params)
  }),env);
  assert.equal(evaluated.status,200);
  const body = await evaluated.json();
  assert.equal(body.researchOnly,true);
  assert.equal(body.evaluation.status,"defer_missing_context");
  assert.equal(body.evaluation.go_recorded,false);
  assert.equal(DB.other,0);
  const denied = await worker.fetch(new Request(origin+"/api/research/evaluate",{
    method:"POST",headers:{Origin:origin,"Content-Type":"application/json"},
    body:JSON.stringify(params)
  }),env);
  assert.equal(denied.status,401);
  const malformed = await worker.fetch(new Request(origin+"/api/research/evaluate",{
    method:"POST",headers:evalHeaders,body:JSON.stringify({seedId:"Q-BAS-001",selections:{unknown:"yes"}})
  }),env);
  assert.equal(malformed.status,400);
  const badOrigin = await worker.fetch(new Request(origin+"/api/research/evaluate",{
    method:"POST",headers:{...evalHeaders,Origin:"https://evil.example"},
    body:JSON.stringify(params)
  }),env);
  assert.equal(badOrigin.status,403);
  assert.equal(DB.other,0);
});
